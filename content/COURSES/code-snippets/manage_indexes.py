#!/usr/bin/env python3
"""Generate clean, navigable Markdown index.md files for a folder tree.

Examples (run from the repository root):
    python scripts/manage_indexes.py rebuild
    python scripts/manage_indexes.py clean
    python scripts/manage_indexes.py build

Or supply a repository path:
    python scripts/manage_indexes.py rebuild /path/to/SecondBrain

Each generated index contains a title, a folder table of contents, files before
subfolders, H2 headings for folders, relative links, and back-to-top links.
Only generated indexes are removed; hand-written index.md files are preserved.
"""
from pathlib import Path
from urllib.parse import quote
import argparse
import os
import re
import sys

MARKER = "<!-- GENERATED BY manage_indexes.py; DO NOT EDIT MANUALLY -->"
OLD_MARKER = "<!-- GENERATED BY create_indexes.py; DO NOT EDIT MANUALLY -->"
GENERATED_MARKERS = (MARKER, OLD_MARKER)
INDEX_NAME = "index.md"
SKIP_DIRS = {
    ".git", ".hg", ".svn", "__pycache__", ".cache", ".pytest_cache",
    ".mypy_cache", "node_modules", ".venv", "venv"
}


def folders_under(root: Path):
    """Yield each included directory once; never follow symlinks."""
    for current, dirs, _files in os.walk(root, topdown=True, followlinks=False):
        current_path = Path(current)
        dirs[:] = sorted(
            [name for name in dirs
             if name not in SKIP_DIRS and not (current_path / name).is_symlink()],
            key=str.casefold,
        )
        yield current_path


def children_of(folder: Path):
    """Return visible immediate children, with files sorted before folders."""
    try:
        entries = list(folder.iterdir())
    except OSError as exc:
        print(f"WARNING: cannot read {folder}: {exc}", file=sys.stderr)
        return []
    result = []
    for item in entries:
        if item.is_symlink() or item.name == INDEX_NAME:
            continue
        if item.is_dir():
            if item.name not in SKIP_DIRS:
                result.append(item)
        else:
            result.append(item)
    return sorted(result, key=lambda p: (p.is_dir(), p.name.casefold()))


def relative_link(from_folder: Path, target: Path) -> str:
    rel = os.path.relpath(target, start=from_folder).replace(os.sep, "/")
    return quote(rel, safe="/-._~")


def markdown_label(value: str) -> str:
    """Escape Markdown characters that can break a link label."""
    return re.sub(r"([\\`*{}\[\]<>!|_])", r"\\\1", value)


def slug_part(value: str) -> str:
    """Create a readable, stable anchor fragment from a folder name."""
    value = value.casefold().strip()
    value = re.sub(r"[^a-z0-9 _-]", "", value)
    value = re.sub(r"[\s_]+", "-", value)
    value = re.sub(r"-+", "-", value).strip("-")
    return value or "folder"


def folder_anchor(relative_folder: Path) -> str:
    parts = [slug_part(part) for part in relative_folder.parts if part not in ("", ".")]
    return "folder-" + "-".join(parts)


def folder_tree(root: Path):
    folders = list(folders_under(root))
    return sorted(folders, key=lambda p: (len(p.relative_to(root).parts), p.as_posix().casefold()))


def descendants(folder: Path):
    """Yield descendant folders in stable depth-first order."""
    for current, dirs, _files in os.walk(folder, topdown=True, followlinks=False):
        current_path = Path(current)
        dirs[:] = sorted(
            [name for name in dirs
             if name not in SKIP_DIRS and not (current_path / name).is_symlink()],
            key=str.casefold,
        )
        for name in dirs:
            child = current_path / name
            if child.is_dir() and not child.is_symlink():
                yield child


def render_file_list(index_folder: Path, folder: Path):
    files = [item for item in children_of(folder) if item.is_file()]
    if not files:
        return ["- *No files in this folder.*"]
    return [f"- [{markdown_label(item.name)}]({relative_link(index_folder, item)})" for item in files]


def render_folder_section(index_folder: Path, root: Path, folder: Path, is_root=False):
    """Render this folder's files first, then child folders as H2 sections."""
    lines = []
    relative = folder.relative_to(root)
    display_name = folder.name
    if not is_root:
        anchor = folder_anchor(relative)
        lines.extend([f'<a id="{anchor}"></a>', "", f"## {display_name}", ""])
        lines.extend([f"*Path:* `{relative.as_posix()}`", ""])

    lines.extend(["### Files", ""])
    lines.extend(render_file_list(index_folder, folder))
    lines.append("")

    child_folders = [item for item in children_of(folder) if item.is_dir()]
    for child in child_folders:
        lines.extend(render_folder_section(index_folder, root, child, is_root=False))

    if not is_root:
        lines.extend(["[↑ Back to top](#top)", ""])
    return lines


def render_index(folder: Path, root: Path) -> str:
    title = f"Index of {folder.name}"
    lines = [
        MARKER,
        '<a id="top"></a>',
        "",
        f"# {title}",
        "",
        f"*Folder:* `{folder.name}`",
        "",
        "## Table of contents",
        "",
    ]
    all_descendants = list(descendants(folder))
    if all_descendants:
        for child in all_descendants:
            rel = child.relative_to(folder)
            indent = "  " * (len(rel.parts) - 1)
            lines.append(f"{indent}- [{markdown_label(child.name)}](#{folder_anchor(rel)})")
    else:
        lines.append("- *No subfolders.*")
    lines.extend(["", "---", ""])
    lines.extend(render_folder_section(folder, root, folder, is_root=True))
    lines.extend(["", "[↑ Back to top](#top)", ""])
    return "\n".join(lines)


def clean(root: Path) -> int:
    removed = 0
    for folder in list(folders_under(root)):
        index = folder / INDEX_NAME
        if not index.is_file() or index.is_symlink():
            continue
        try:
            contents = index.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            continue
        if any(marker in contents for marker in GENERATED_MARKERS):
            try:
                index.unlink()
                print(f"DELETED: {index}")
                removed += 1
            except OSError as exc:
                print(f"ERROR deleting {index}: {exc}", file=sys.stderr)
    print(f"Removed {removed} generated index file(s).")
    return removed


def build_one(folder: Path, root: Path) -> bool:
    index = folder / INDEX_NAME
    if index.exists():
        try:
            old = index.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            print(f"ERROR reading {index}: {exc}", file=sys.stderr)
            return False
        if not any(marker in old for marker in GENERATED_MARKERS):
            print(f"SKIP (preserving hand-written index): {index}")
            return True
    try:
        index.write_text(render_index(folder, root), encoding="utf-8")
        print(f"CREATED/UPDATED: {index}")
        return True
    except OSError as exc:
        print(f"ERROR writing {index}: {exc}", file=sys.stderr)
        return False


def main():
    parser = argparse.ArgumentParser(description="Generate polished Markdown indexes for a folder tree.")
    parser.add_argument("command", choices=("clean", "build", "rebuild"))
    parser.add_argument("root", nargs="?", default=".", help="Repository root (default: current directory)")
    args = parser.parse_args()
    root = Path(args.root).expanduser().resolve()
    if not root.is_dir():
        print(f"ERROR: not a folder: {root}", file=sys.stderr)
        sys.exit(2)
    if args.command in ("clean", "rebuild"):
        clean(root)
    if args.command in ("build", "rebuild"):
        folders = folder_tree(root)
        ok = True
        for folder in folders:
            if not build_one(folder, root):
                ok = False
        print(f"Processed {len(folders)} folder(s).")
        if not ok:
            sys.exit(1)


if __name__ == "__main__":
    main()
